# Aula 04 - Soma e juntando números

print(4+5)
# Aqui temos a soma dos dois valores, sua saída será 9.

print('4'+'5')
# Aqui temos a junção dos dois valores (através do operador +), sua saída será 45.

print(' Olá', 5)
# Para juntar uma mensagem com um número, é possível usando a vírgula, sua saída será Olá 5. Não é possível com o operador +.