# Aula 06 - Tipos primitivos e Saída de Dados

n1 = int(input('Digite um número: ')) # int é usado para representar e converter números inteiros
n2 = int(input('Digite outro número: '))
soma = n1 + n2
print(f'A soma entre {n1} e {n2} vale {soma}') # o 'f' antes das aspas indica que é o antigo '.format', que permite colocar variáveis dentro de uma string.

# int = números inteiros (-2, 0, 4, 17)
# float = números reais (4.6, -5.3, 0.0, 23.4)
# bool = valores lógicos (True ou False)
# str = textos (qualquer coisa entre aspas simples ou duplas)
