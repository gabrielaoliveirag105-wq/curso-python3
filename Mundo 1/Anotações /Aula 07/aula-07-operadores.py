# Aula 07 - Operações Aritméticos
# Exemplo de operadores:
print(5 + 2) # Adição
print(5 - 2) # Subtração
print(5 * 2) # Multiplicação
print(5 / 2) # Divisão
print(5 ** 2) # Potência
print(5 // 2) # Divisão inteira - a parte inteira do resultado da divisão
print(5 % 2) # Resto da divisão - o que sobra da divisão inteira

