# Aula 11 - Colocando em prática

# Testando cores: 
print('\033[4;45mOlá, Mundo!\033[m') # \033[m no final o fundo até o final do texto, não ultrapassa disso.

print('\033[7;40mVamos fazer um texto preto com branco?\033[m') # Inversão de cores

print('\033[7;33;44mTexto amarelo com fundo azul\033[m') # Invertendo a ordem - o 7 faz inversão de cores.

