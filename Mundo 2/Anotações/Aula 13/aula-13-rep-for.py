# Aula 13 - Estrutura de Repetição (for)
# - Laço de variável com controle

# - Laço c no intervalo (1,10)
#       passo (aqui é onde temos a ação do que será feito) 
#    pega (pega está fora do laço sempre irá se repetir)

# -> Nós lemos como: faça um laço c (contador) para contar entre 1 até 10

# Em Python:
for c in range (1,10): # lê o c de 1 até 10
    print(c)           # aqui realiza a contagem (repetição)
print('Saindo do programa!') # o programa se encerra aqui, e essa mensagem sempre vai se repetir.




