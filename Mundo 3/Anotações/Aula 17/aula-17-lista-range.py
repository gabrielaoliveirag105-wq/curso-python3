# Aula 17 - Lista com range
# Range cria uma estrutura já organizada e ordenada.

valores = list(range(4,11)) # ele mostra os elementos de 4 até 11 - eliminando sempre o último elemento
print(valores)

valores = [8,2,5,4,9,3,0]
valores.sort() # organiza os elementos de forma ordenada
valores.sort(reverse=True) # mostra os elementos de forma invertida (decrescente)

print(valores)
print(valores)
